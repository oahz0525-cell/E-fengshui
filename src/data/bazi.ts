import type { BaziResult } from '@/types';

const G = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
const Z = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];

function days1900(y: number, m: number, d: number): number {
  let days = 0;
  for (let yr = 1900; yr < y; yr++) days += (yr % 4 === 0 && yr % 100 !== 0) || yr % 400 === 0 ? 366 : 365;
  const md = [31, ((y % 4 === 0 && y % 100 !== 0) || y % 400 === 0) ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  for (let mn = 1; mn < m; mn++) days += md[mn - 1];
  return days + d - 1;
}

export function calcBazi(y: number, m: number, d: number, h: number): BaziResult {
  const ds = days1900(y, m, d);
  const yG = (y - 4) % 10, yZ = (y - 4) % 12;
  const dG = ((ds % 10) + 10) % 10, dZ = ((ds % 12) + 12) % 12;
  const mT = [
    ['丙', '丁', '戊', '己', '庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁'],
    ['戊', '己', '庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁', '戊', '己'],
    ['庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁', '戊', '己', '庚', '辛'],
    ['壬', '癸', '甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'],
    ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸', '甲', '乙'],
  ];
  const mR = mT[yG % 5][m - 1];
  const hZ = Math.floor((h + 1) / 2) % 12;
  const hT = [
    ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸', '甲', '乙'],
    ['丙', '丁', '戊', '己', '庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁'],
    ['戊', '己', '庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁', '戊', '己'],
    ['庚', '辛', '壬', '癸', '甲', '乙', '丙', '丁', '戊', '己', '庚', '辛'],
    ['壬', '癸', '甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'],
    ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸', '甲', '乙'],
  ];
  const hR = hT[dG % 5][hZ];
  return {
    yG: G[yG], yZ: Z[yZ], mG: G[G.indexOf(mR)], mZ: Z[(m + 1) % 12],
    dG: G[dG], dZ: Z[dZ], hG: G[G.indexOf(hR)], hZ: Z[hZ],
    dm: G[dG],
  };
}
